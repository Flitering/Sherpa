// Перестроение маршрута под текущую позицию игрока.
//
// Позиция приходит из имён скриншотов: игрок делает их вручную, часто и не всегда «в пути»
// (скрин в дверях, скрин «чтобы показать, где я»). Маршрут из-за каждого такого скрина
// пересобирать нельзя: точки начнут гулять туда-сюда, а реальные пути по сетке считаются
// заново — это заметно по производительности. Поэтому перестраиваем только когда это
// действительно нужно:
//   1. от точки, относительно которой считали маршрут, отошли дальше MOVE_M;
//   2. новый порядок оставшихся точек короче старого не меньше чем на SAVE_M
//      (или целей в маршруте стало больше — из новой точки в бюджет рейда влезло больше);
//   3. с прошлого перестроения прошло COOLDOWN_MS — иначе маршрут «машет хвостом»
//      и игрок перестаёт понимать, куда идти;
//   4. либо игрок дошёл до одного из мест цели: у цели мест часто несколько (несколько медиков,
//      несколько контейнеров, несколько зон), и он мог подойти к другому месту — тогда активной
//      делаем ту цель, к чьему месту он встал рядом (пороги NEAR_* ниже). Это правило пороги 1 и 3
//      НЕ сдерживают: встал рядом с целью — маршрут должен повести к ней сразу, а не через минуту.
// Порядок сравниваем по прямой (со штрафом за этажи) — та же метрика, на которой маршрут
// планируется; путь к ближайшей цели навигатор считает по сетке сам.

import type { Vec3 } from "../types";
import { dist, pathLength } from "./route";

/** Сколько метров можно отойти от точки, от которой построен маршрут, прежде чем думать о перестроении. */
export const MOVE_M = 45;
/** Минимальная экономия (м), ради которой стоит перестроить маршрут и пересчитать пути. */
export const SAVE_M = 60;
/** Пауза между перестроениями, мс: скриншоты делают часто, маршруту нужно дать постоять. */
export const COOLDOWN_MS = 60_000;
/**
 * Игрок встал рядом с местом цели (м) — раз уж пришёл, это место и делаем текущим, даже если
 * маршрут от него чуть длиннее. У зоны точка — её центр, поэтому для зон порог больше, чем для
 * конкретного места (контейнер, медик, выключатель).
 */
export const NEAR_ZONE_M = 60;
export const NEAR_ITEM_M = 30;
/** Насколько новое место должно быть ближе того, к которому вели сейчас: иначе две одинаково близкие
 *  точки заставят маршрут мотать хвостом между ними. */
export const NEAR_MARGIN_M = 15;

/** Сколько игрок отошёл от точки, от которой построен маршрут (м). Бесконечность — точки ещё нет. */
export function movedFrom(anchor: Vec3 | undefined, at: Vec3 | undefined): number {
    return !anchor || !at ? Infinity : dist(anchor, at);
}

/** Порядок обхода, оценённый от одной и той же точки. */
export interface RouteShape {
    /** Точка, от которой считаем путь — всегда текущая позиция игрока, чтобы сравнение было честным. */
    from: Vec3;
    /** Точки маршрута в порядке обхода (только оставшиеся цели). */
    points: Vec3[];
    /** Выход, к которому ведут маршрут. */
    exit?: Vec3;
}

/**
 * Перестраивать ли маршрут под позицию `from`: старый порядок против нового, оба от неё.
 * Экономия считается от одной точки, иначе она «бумажная» — старый маршрут строился из другой.
 */
export function worthReordering(old: RouteShape, neu: RouteShape): { yes: boolean; savedM: number } {
    const savedM = pathLength(old.points, old.from, old.exit) - pathLength(neu.points, neu.from, neu.exit);
    const same =
        old.points.length === neu.points.length &&
        old.points.every((p, i) => {
            const q = neu.points[i];
            return !!q && Math.abs(p.x - q.x) < 0.5 && Math.abs(p.z - q.z) < 0.5 && Math.abs(p.y - q.y) < 0.5;
        });
    const more = neu.points.length > old.points.length;
    return { yes: !same && (savedM >= SAVE_M || (more && savedM >= -SAVE_M)), savedM };
}

/** Место цели: у одной цели их бывает несколько («Фельдшер» — несколько медиков, предмет — несколько контейнеров). */
export interface Spot {
    position: Vec3;
    kind: "zone" | "item";
}

/**
 * Ближайшее к игроку непроверенное место среди мест целей `stops`, до которого он действительно
 * дошёл (для зон и конкретных мест — свои пороги). Индекс — позиция цели в переданном массиве.
 * Мест, где игрок уже был и ничего не нашёл, в целях уже нет (их убирает dropSpot), поэтому
 * здесь только те, что ещё не проверены.
 */
export function nearSpot(stops: { points: Spot[] }[], at: Vec3): { index: number; point: Vec3; d: number } | undefined {
    let best: { index: number; point: Vec3; d: number } | undefined;
    for (let index = 0; index < stops.length; index++) {
        for (const p of stops[index].points) {
            const d = dist(at, p.position);
            if (d > (p.kind === "zone" ? NEAR_ZONE_M : NEAR_ITEM_M)) continue;
            if (!best || d < best.d) best = { index, point: p.position, d };
        }
    }
    return best;
}
